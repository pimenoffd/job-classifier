"""Tests for the normalization pipeline (docs/PLAN.md §2, §4.1, §4.2).

One test per noise type from PLAN.md §2, plus the three mandatory cases from
§7 step 2.  Most assertions are written as "raw form normalizes to the same
string as the canonical classifier form", because that is exactly the property
matcher.py (Task 3) relies on.
"""

import re

import pytest
import snowballstemmer

from job_classifier.dictionaries import load_classifier
from job_classifier.normalize import normalize

_STEMMER = snowballstemmer.stemmer("russian")
_TOKEN_RE = re.compile(r"[a-zа-я0-9]+")


def plain(text: str) -> str:
    """Lowercase + tokenize + stem + dedupe, with no dictionary rules applied.

    Used to assert that non-construction titles pass through the pipeline
    untouched (no rule and no token correction may rewrite them).
    """
    tokens = _TOKEN_RE.findall(text.lower().replace("ё", "е"))
    return " ".join(dict.fromkeys(_STEMMER.stemWords(tokens)))


# --------------------------------------------------------------------------
# Mandatory cases (PLAN.md §7 step 2 verify line)
# --------------------------------------------------------------------------


def test_mandatory_typo_inside_phrase_synonym():
    """§4.1: token correction must repair a typo *inside* a phrase rule."""
    result = normalize("Произвдоитель работ")
    assert result == normalize("Прораб")
    assert result == "прораб"


def test_mandatory_technique_before_role():
    """§4.2: `машинист автокрана` must keep the technique word."""
    result = normalize("машинист автокрана")
    assert result == normalize("Машинист крана автомобильного")
    assert "автомобильн" in result
    # Must be distinguishable from the other two cranes in the classifier.
    assert result != normalize("Машинист башенного крана")
    assert result != normalize("Машинист гусеничного крана")


def test_mandatory_space_shift():
    """The misplaced space must be repaired token-by-token: `инжене рпо` -> `инженер по`."""
    result = normalize("ИНЖЕНЕ РПО ОХРАНЕ ТРУДА")
    assert result == normalize("Инженер по охране труда")
    assert result == "инженер по охран труд"
    assert {"инженер", "по", "охран", "труд"} == set(result.split())


