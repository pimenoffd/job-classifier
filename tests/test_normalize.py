def test_normalize_is_idempotent():
    for raw in ["Маш. катка", "машинист автокрана", "Произвдоитель работ", "ПЛОТНИК"]:
        once = normalize(raw)
        assert normalize(once) == once


def test_empty_and_punctuation_only_input():
    assert normalize("") == ""
    assert normalize("   ") == ""
    assert normalize("--- ()") == ""


def test_every_classifier_name_normalizes_to_a_distinct_form():
    forms = {normalize(name) for _, name in load_classifier()}
    assert len(forms) == 56
