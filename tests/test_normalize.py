@pytest.mark.parametrize("title", OFFICE_TITLES)
def test_office_titles_pass_through_untouched(title):
    """No rule and no token correction may rewrite a non-construction title."""
    assert normalize(title) == plain(title)


@pytest.mark.parametrize(
    "raw, clean",
    [
        ("Агроом", "Агроном"),
        ("Диспетче автотранспорта", "Диспетчер автотранспорта"),
        ("Кладощвик центрального склада", "Кладовщик центрального склада"),
        ("КУРЬЕР 4 РАЗРЯДА", "Курьер"),
        ("  Программист 1С 2 категории ", "Программист 1С"),
    ],
)
def test_noisy_office_titles_gain_no_construction_tokens(raw, clean):
    classifier_tokens = set()
    for _, name in load_classifier():
        classifier_tokens.update(normalize(name).split())
    head = normalize(raw).split()[0]
    assert head not in classifier_tokens
    assert head == plain(clean).split()[0] or head == plain(raw).split()[0]


